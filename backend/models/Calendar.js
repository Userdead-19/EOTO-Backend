import mongoose from "mongoose"

const calendarSchema = new mongoose.Schema(
  {
    userId: {
      type: mongoose.Schema.Types.ObjectId,
      ref: "User",
      required: true,
    },
    title: {
      type: String,
      required: true,
    },
    description: {
      type: String,
      default: "",
    },
    startDate: {
      type: Date,
      required: true,
    },
    endDate: {
      type: Date,
      required: true,
    },
    type: {
      type: String,
      enum: ["event", "deadline", "meeting"],
      default: "event",
    },
  },
  { timestamps: true },
)

export default mongoose.model("Calendar", calendarSchema)
